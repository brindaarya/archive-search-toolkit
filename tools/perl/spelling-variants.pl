# Вернуть замену с тем же регистром: ВСЕ ЗАГЛАВНЫЕ, Первая заглавная или строчные.
sub _case_like {
  my ($orig, $new) = @_;
  return uc $new if length($orig) > 1 && $orig eq uc $orig;
  return ucfirst $new if substr($orig, 0, 1) eq uc substr($orig, 0, 1);
  return $new;
}

sub _apply_table {
  my ($table, $word) = @_;
  my $lc = lc $word;
  for my $r (@$table) {
    my ($re, $repl) = @$r;
    if (my @m = $lc =~ $re) {
      my $new = $repl;
      my $i = 1;
      $new =~ s/\$(\d)/defined $m[$1 - 1] ? $m[$1 - 1] : ''/ge;
      return _case_like($word, $new);
    }
  }
  return $word;
}

# Одно слово (последовательность кириллических букв) → старый вариант по флагам.
sub old_word {
  my ($w, $on, $next_char) = @_;
  my $orig = $w;

  $w =~ tr/ёЁ/еЕ/ if $on->{yo};

  # корневые правила (ять, фита) — до окончаний, они смотрят на целое слово
  $w = _apply_table(\@YAT,  $w) if $on->{yat};
  $w = _apply_table(\@FITA, $w) if $on->{fita};

  # предложный/дательный падеж: «в Быкове» → «въ Быковѣ» (кроме -ане/-яне — это
  # именительный множественного: «крестьяне», и слов, где -ие меняется на -іи)
  if ($on->{loc} && $w =~ /[$CONS]е$/i && $w !~ /(?:ан|ян|ин)е$/i && length($w) > 3) {
    $w =~ s/е$/ѣ/;
    $w =~ s/Е$/Ѣ/;
  }

  # окончания прилагательных и причастий
  if ($on->{ago}) {
    $w =~ s/(?<=[$CONS])ого$/аго/i unless $w =~ /^(?:одного|такого|никакого|какого|другого|своего|этого|того|всего)$/i;
    $w =~ s/(?<=[жчшщц])его$/аго/i;
    $w =~ s/(?<=[нр])его$/яго/i if length($w) > 5;
  }
  if ($on->{plural}) {
    $w =~ s/ые$/ыя/;
    $w =~ s/(?<=[кгхжчшщ])ие$/ия/;       # «метрические» → «метрическія» (после буквы-согласной)
  }

  # и → і перед гласной и «й»; вне зависимости от положения в слове
  if ($on->{i}) {
    $w =~ s/и(?=[$VOWEL])/і/g;
    $w =~ s/И(?=[$VOWEL])/І/g;
    if ($on->{iy}) {                      # Йога → Іога (иностранные слова на «й» + гласная)
      $w =~ s/^й(?=[аеёиоуыэюя])/і/;
      $w =~ s/^Й(?=[аеёиоуыэюя])/І/;
    }
  }

  # твёрдый знак в конце слова
  if ($on->{hard} && $w =~ /[$CONS]$/i) {
    my $abbr = (defined $next_char && $next_char eq '.' && length($w) <= 3);
    unless ($abbr) {
      $w .= ($w eq uc $w && length($w) > 1) ? 'Ъ' : 'ъ';
    }
  }

  return $w;
}

sub old_phrase {
  my ($phrase, $on) = @_;
  my @parts = split /([А-Яа-яЁё]+)/, $phrase;
  my $out = '';
  for my $k (0 .. $#parts) {
    if ($parts[$k] =~ /^[А-Яа-яЁё]+$/) {
      my $next = $k < $#parts ? substr($parts[$k + 1], 0, 1) : undef;
      $out .= old_word($parts[$k], $on, $next);
    } else {
      $out .= $parts[$k];
    }
  }
  return $out;
}

# Начальное «й» после 1918 г. печатали и распознавали как «и»: «иога» давала вдвое
# больше находок, чем «йога».
sub post1918_phrase {
  my ($phrase) = @_;
  (my $p = $phrase) =~ s/(?<![А-Яа-яЁё])й(?=[аеёиоуыэюя])/и/g;
  $p =~ s/(?<![А-Яа-яЁё])Й(?=[аеёиоуыэюя])/И/g;
  return $p;
}

# --- публичный интерфейс --------------------------------------------------

sub spelling_variants {
  my ($phrase) = @_;
  $phrase =~ s/^\s+|\s+$//g;

  my @presets = (
    [ 'как введено',                           undef ],
    [ 'ё→е',                                    { yo => 1 } ],
    [ 'полная старая орфография',               { yo=>1, yat=>1, fita=>1, loc=>1, ago=>1, plural=>1, i=>1, iy=>1, hard=>1 } ],
    [ 'старая, без падежных ѣ и окончаний',     { yo=>1, yat=>1, fita=>1, i=>1, iy=>1, hard=>1 } ],
    [ 'ъ + і, без ѣ (как часто распознаёт OCR)', { yo=>1, fita=>1, i=>1, iy=>1, hard=>1 } ],
    [ 'только ъ',                               { yo=>1, hard=>1 } ],
    [ 'только і',                               { yo=>1, i=>1, iy=>1 } ],
    [ 'ѣ без ъ и і',                            { yo=>1, yat=>1, fita=>1, loc=>1 } ],
    [ 'после 1918 г.: «и» вместо начального «й»', 'post1918' ],
  );

  my (%seen, @out);
  for my $p (@presets) {
    my ($note, $flags) = @$p;
    my $text = !defined $flags      ? $phrase
             : ref $flags eq ''     ? post1918_phrase($phrase)
             :                        old_phrase($phrase, $flags);
    next if $seen{$text}++;
    push @out, { text => $text, note => $note };
  }
  return @out;
}

# --- запуск из командной строки -------------------------------------------

unless (caller) {
  binmode(STDOUT, ':encoding(UTF-8)');
  binmode(STDERR, ':encoding(UTF-8)');
  my @args = map { decode('UTF-8', $_) } @ARGV;
  my ($plain, $or, $explain);
  my @words;
  for my $a (@args) {
    if    ($a eq '--plain')   { $plain = 1 }
    elsif ($a eq '--or')      { $or = 1 }
    elsif ($a eq '--explain') { $explain = 1 }
    elsif ($a eq '-h' || $a eq '--help') {
      print "Использование: perl spelling-variants.pl [--plain|--or|--explain] 'фраза'\n";
      exit 0;
    }
    else { push @words, $a }
  }
  die "Нужна фраза: perl spelling-variants.pl 'фраза'\n" unless @words;

  my @v = spelling_variants(join ' ', @words);
  if ($or) {
    print join(' ', map { '"' . $_->{text} . '"' } @v), "\n";
  } elsif ($plain) {
    print "$_->{text}\n" for @v;
  } else {
    my $n = 0;
    printf "%d. %s%s\n", ++$n, $_->{text}, $explain ? "   — $_->{note}" : '' for @v;
  }
}

1;
