# Поисковики архивов (Яндекс Архив, ГПИБ и др.) не приводят «ѣ», «і», «ъ» к
# современным буквам: запрос «йога» находил 10 страниц, «іога» — 277. Этот скрипт
# берёт фразу в современной орфографии и выдаёт ранжированный список вариантов,
# которые стоит прогнать. Правила — в docs/02-дореволюционная-орфография.md.
#
# Это эвристика, а не словарь: угадывает не всё (особенно ять в редких словах).
# Поэтому варианты принято проверять пробой — сравнить число находок по каждому
# (ya-probe.pl делает это для Яндекс Архива).
#
# Запуск:
#   perl spelling-variants.pl 'в Бронницком уезде'
#   perl spelling-variants.pl --plain 'Фёдор Ильин'      # только строки вариантов
#   perl spelling-variants.pl --or 'исповедные ведомости' # одной строкой для поиска с OR (ГПИБ)
#   perl spelling-variants.pl --explain 'метрические книги'
#
# Как модуль:
#   require 'spelling-variants.pl';
#   my @v = spelling_variants('Бронницкий уезд');   # [ {text=>..., note=>...}, ... ]

